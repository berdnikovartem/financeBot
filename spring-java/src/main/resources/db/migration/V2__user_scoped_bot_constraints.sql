CREATE TABLE IF NOT EXISTS app_users (
    id BIGSERIAL PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    bitunix_api_key_encrypted VARCHAR(4096),
    bitunix_api_secret_encrypted VARCHAR(4096)
);

CREATE TABLE IF NOT EXISTS bot_configs (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT,
    symbol VARCHAR(255) NOT NULL,
    parameters JSONB,
    price_step_percentage DOUBLE PRECISION,
    last_long_price DOUBLE PRECISION,
    last_short_price DOUBLE PRECISION,
    active BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS asset (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

ALTER TABLE bot_configs ADD COLUMN IF NOT EXISTS user_id BIGINT;
ALTER TABLE bot_configs ADD COLUMN IF NOT EXISTS parameters JSONB;
ALTER TABLE bot_configs ADD COLUMN IF NOT EXISTS price_step_percentage DOUBLE PRECISION;
ALTER TABLE bot_configs ADD COLUMN IF NOT EXISTS last_long_price DOUBLE PRECISION;
ALTER TABLE bot_configs ADD COLUMN IF NOT EXISTS last_short_price DOUBLE PRECISION;
ALTER TABLE bot_configs ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE bot_configs DROP CONSTRAINT IF EXISTS bot_configs_symbol_key;
ALTER TABLE bot_configs DROP CONSTRAINT IF EXISTS uk_bot_configs_user_symbol;
ALTER TABLE bot_configs DROP CONSTRAINT IF EXISTS bot_configs_user_id_fkey;
ALTER TABLE bot_configs ADD CONSTRAINT bot_configs_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES app_users(id);

CREATE UNIQUE INDEX IF NOT EXISTS uk_bot_configs_user_symbol
    ON bot_configs (user_id, symbol)
    WHERE user_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    token_type VARCHAR(32) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);